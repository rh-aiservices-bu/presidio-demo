"use strict";

const $ = (sel) => document.querySelector(sel);
const el = (tag, cls, text) => {
  const node = document.createElement(tag);
  if (cls) node.className = cls;
  if (text !== undefined) node.textContent = text;
  return node;
};

const SVG = "http://www.w3.org/2000/svg";
const svgEl = (tag, attrs = {}) => {
  const node = document.createElementNS(SVG, tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, String(v));
  return node;
};

const state = {
  mode: "none",
  catalog: [],
  enabled: new Set(),
  applied: new Set(),
  editable: false,
  pollTimer: null,
  turns: 0,
  // handle -> {value, entityType, turn}. Accumulated across the session so a handle
  // from turn 1 is still readable at turn 5. Lives only here, in this tab: the server
  // sends it per turn and keeps nothing, and it is never written to a trace.
  mapping: new Map(),
  mappingSupported: null,
  // Scopes the server-side handle registry, so <PERSON_1> keeps meaning one person
  // for this tab's whole conversation. Per tab, and regenerated by Clear chat.
  sessionId: newSessionId(),
};

function newSessionId() {
  if (window.crypto?.randomUUID) return window.crypto.randomUUID();
  return `s-${Date.now()}-${Math.random().toString(36).slice(2, 10)}`;
}

